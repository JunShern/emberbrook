// route_overlay.js — THE LEGIBILITY OVERLAY. Draws the town's INTENDED route over the
// live game so "where is a player supposed to walk here?" stops being a matter of opinion.
//
//   R          off -> this shot -> off
//   Shift+R    off -> this shot -> EVERY shot -> off   (how you tell "the exit is
//              off-screen" from "the exit leads somewhere that isn't built yet")
//
// GREEN = an entry (somewhere a player materialises in this shot), ORANGE = an exit (a
// seam, a door, a portal), plus the exit's trigger BAND drawn at its real width, an arrow
// along the direction the path leaves by, and the route itself as a ribbon just above the
// ground. Warm ribbon = the through-route (spine), pale blue = a spur to a destination,
// RED CENTRELINE = a way on that LOOKS walkable and is not (the map's maintenance ladders
// and cargo winch ship no walk ribbon — a legibility trap worth seeing).
//
// DATA: public/townmap/<town>.routes.json, generated by tools/routes_derive.mjs from the
// town map's typed walk edges + cameras.json ownership + world/scenegraph.json. Nothing
// here is authored in code: no shot id, no coordinate, no colour, no label.
//
// THREE RULES IT KEEPS:
//  1. NEVER touches game state. It adds one THREE.Group to `scene` and reads SIM. It is
//     never pushed into collide/walkRef/allMeshes (same discipline as the zones overlay in
//     play3d.html), so it can never become a floor, a wall or an occluder.
//  2. LAZY. Nothing is fetched, built or added until R is pressed the first time. With the
//     overlay off the cost is one keydown listener.
//  3. DEPTH-HONEST. Markers and ribbons are depthTest:true, so the shot's own baked depth
//     map hides whatever the BACKDROP hides. An entry the player cannot see is an entry
//     this overlay must not show either — that is the whole point of the audit.
//
// Works in del-cine (per-shot) and in real-time scenes like townwalk (no shots: draws the
// whole town). No-ops silently when the data file is absent or has nothing for the scene.
//
// window.ROUTES — the audit instrument, reusable by any agent:
//   ROUTES.toggle(v) / ROUTES.mode('off'|'shot'|'all') / ROUTES.shot() / ROUTES.data()
//   ROUTES.probe()      GL READBACK visibility of every entry/exit/route sample in the
//                       current shot, measured against the shot's OWN baked depth map
//                       (screenshots of a hidden tab are stale — pixels are ground truth)
//   ROUTES.dropEdges()  every unprotected fall-off within reach of the route, with coords
//   ROUTES.summary()    the two above, folded into one per-shot verdict record
(function () {
  'use strict';
  var KEY = 'r', LIFT, D, DATA = null, TRIED = false, SRC = null;
  var MODE = 'off', GROUP = null, BUILT = {}, LEGEND = null;

  // play3d.html is a classic script, so its top-level `let`/`const` live in the shared
  // global lexical scope and are readable from here — but a missing one is a ReferenceError,
  // so every read is guarded. A binding that is gone disables the overlay; it never throws
  // into the page.
  var TH = function () { try { return THREE; } catch (e) { return window.THREE; } };
  var SCN = function () { try { return scene; } catch (e) { return null; } };
  var REN = function () { try { return R; } catch (e) { return null; } };
  var CAM = function () { try { return cam; } catch (e) { return null; } };
  var CH = function () { try { return ch; } catch (e) { return null; } };
  var SKEY = function () {
    var s = null; try { s = SCENE; } catch (e) {}
    return s || new URLSearchParams(location.search).get('scene') || '';
  };
  var GRAPH = function () { try { return SG; } catch (e) { return null; } };
  var SIM = function () { return window.SIM || null; };
  // the live shot id, or '*' in a scene that has no shots at all
  function shotId() {
    var c = window.__cine;
    return (c && c.cam) || '*';
  }

  // ------------------------------------------------------------------ data ----
  // Resolve the routes file WITHOUT a hard-coded town: every scene-graph node states its
  // own provenance ("townmap/<town>.map.json (town '<town>')") and the graph lists its
  // sources, so the candidate list is derived. A file is accepted only if it claims this
  // scene in `appliesTo` (or ships a '*' shot). Generalises to Emberbrook and beyond.
  function candidates() {
    var out = [], q = new URLSearchParams(location.search), sk = SKEY(), G = GRAPH();
    if (q.get('routes')) out.push(q.get('routes'));
    var seen = {}, add = function (t) { if (t && !seen[t]) { seen[t] = 1; out.push('townmap/' + t + '.routes.json'); } };
    var node = G && G.nodes && G.nodes[sk], m;
    if (node && node.origin && (m = /townmap\/([\w.-]+)\.map\.json/.exec(node.origin))) add(m[1]);
    if (G && G.sources) G.sources.forEach(function (s) {
      var k = /townmap\/([\w.-]+)\.map\.json/.exec(s); if (k) add(k[1]);
    });
    if (sk) add(sk);
    return out;
  }
  function load() {
    if (DATA || TRIED) return Promise.resolve(DATA);
    TRIED = true;
    var list = candidates(), sk = SKEY();
    var next = function (i) {
      if (i >= list.length) return null;
      return fetch(list[i] + '?v=' + Date.now()).then(function (r) { return r.ok ? r.json() : null; })
        .catch(function () { return null; })
        .then(function (j) {
          var claims = j && (!j.appliesTo || j.appliesTo.indexOf(sk) >= 0 || (j.shots && j.shots['*']));
          if (claims) { SRC = list[i]; return j; }
          return next(i + 1);
        });
    };
    return Promise.resolve(next(0)).then(function (j) {
      DATA = j;
      if (!j) { console.log('routes overlay: no route data for scene "' + sk + '" (tried ' + list.join(', ') + ')'); return null; }
      D = j.defaults || {}; LIFT = D.lift === undefined ? 0.18 : D.lift;
      return j;
    });
  }
  // which shot records to draw: the live shot, or — in a scene without shots — all of them
  function wanted() {
    if (!DATA || !DATA.shots) return [];
    var id = shotId(), ids = Object.keys(DATA.shots);
    if (MODE === 'all') return ids;
    if (DATA.shots[id]) return [id];
    if (DATA.shots['*']) return ['*'];
    return id === '*' ? ids : [];        // real-time scene: the whole town is on screen
  }

  // ------------------------------------------------------------- geometry ----
  // Snap a route vertex to the floor the player will actually stand on. The map's own
  // height is right to a few centimetres, but the ribbon meshes float ~0.09 over a
  // notched profile, so asking the runtime keeps the line ON the boards even if the
  // geometry is re-baked under us.
  function floorAt(p) {
    var S = SIM(); if (!S) return p[1];
    var ys = [];
    try { ys = S.walkFloors(p[0], p[2]) || []; } catch (e) {}
    if (!ys.length) { try { ys = S.floors(p[0], p[2]) || []; } catch (e) {} }
    var best = null;
    for (var i = 0; i < ys.length; i++) if (Math.abs(ys[i] - p[1]) < 1.6 &&
      (best === null || Math.abs(ys[i] - p[1]) < Math.abs(best - p[1]))) best = ys[i];
    return best === null ? p[1] : best;
  }
  function lifted(pts) {
    var out = [];
    for (var i = 0; i < pts.length; i++) out.push([pts[i][0], floorAt(pts[i]) + LIFT, pts[i][2]]);
    return out;
  }
  var col = function (hex, dflt) { return new (TH().Color)('#' + (hex || dflt)); };
  function mat(hex, dflt, o) {
    o = o || {};
    return new (TH().MeshBasicMaterial)({
      color: col(hex, dflt), transparent: true, opacity: o.opacity === undefined ? 0.62 : o.opacity,
      depthTest: o.depthTest === undefined ? true : o.depthTest, depthWrite: false,
      side: TH().DoubleSide });
  }
  function lineMat(hex, dflt, o) {
    o = o || {};
    return new (TH().LineBasicMaterial)({
      color: col(hex, dflt), transparent: true, opacity: o.opacity === undefined ? 0.95 : o.opacity,
      depthTest: o.depthTest === undefined ? true : o.depthTest, depthWrite: false });
  }
  function line(pts, m) {
    var T = TH(), a = [];
    for (var i = 0; i < pts.length; i++) a.push(pts[i][0], pts[i][1], pts[i][2]);
    var geo = new T.BufferGeometry();
    geo.setAttribute('position', new T.Float32BufferAttribute(a, 3));
    return new T.Line(geo, m);
  }
  // A ribbon, not a 1-px line: a hairline cannot answer "does this read as a route", and
  // the width doubles as a preview of the bucket-2 ground language the fix pass will paint.
  function ribbon(pts, w, m) {
    var T = TH(), pos = [], idx = [], h = w / 2;
    for (var i = 0; i < pts.length; i++) {
      var a = pts[Math.max(0, i - 1)], b = pts[Math.min(pts.length - 1, i + 1)];
      var dx = b[0] - a[0], dz = b[2] - a[2], L = Math.hypot(dx, dz) || 1;
      var px = -dz / L * h, pz = dx / L * h, p = pts[i];
      pos.push(p[0] + px, p[1], p[2] + pz, p[0] - px, p[1], p[2] - pz);
      if (i) { var k = (i - 1) * 2; idx.push(k, k + 1, k + 2, k + 1, k + 3, k + 2); }
    }
    var geo = new T.BufferGeometry();
    geo.setAttribute('position', new T.Float32BufferAttribute(pos, 3));
    geo.setIndex(idx);
    return new T.Mesh(geo, m);
  }
  // Labels are three.js sprites with canvas textures, NOT DOM: a DOM label vanishes from
  // gl.readPixels and from a canvas capture, which are the only trustworthy verification
  // this project has (a hidden tab's composited screenshot is stale).
  function label(text, hex, dflt) {
    var T = TH(), pad = 8, f = 30;
    var c = document.createElement('canvas'), x = c.getContext('2d');
    x.font = 'bold ' + f + 'px monospace';
    var w = Math.ceil(x.measureText(text).width) + pad * 2;
    c.width = w; c.height = f + pad * 2;
    x = c.getContext('2d'); x.font = 'bold ' + f + 'px monospace';
    x.fillStyle = 'rgba(8,6,4,0.72)'; x.fillRect(0, 0, c.width, c.height);
    x.strokeStyle = '#' + (hex || dflt); x.lineWidth = 2; x.strokeRect(1, 1, c.width - 2, c.height - 2);
    x.fillStyle = '#' + (hex || dflt); x.textBaseline = 'middle';
    x.fillText(text, pad, c.height / 2 + 1);
    var tex = new T.CanvasTexture(c);
    tex.minFilter = T.LinearFilter; tex.generateMipmaps = false;
    var s = new T.Sprite(new T.SpriteMaterial({map: tex, transparent: true, depthTest: false,
      depthWrite: false, sizeAttenuation: false}));
    // sizeAttenuation:false -> scale is constant screen size. 0.026 of the frame's
    // half-height reads at ~32 px in the 768-line frame the backdrops are baked at.
    var hh = 0.026 * (D.labelScale || 1);
    s.scale.set(hh * (c.width / c.height) * 0.56, hh, 1);
    s.renderOrder = 1002;
    return s;
  }

  // one marker: ground ring + beacon column (character-height, so it doubles as a scale
  // ruler) + label, and for an exit the trigger band at its true size and an arrow along
  // the direction the path leaves by.
  function marker(m, kind, tag) {
    var T = TH(), grp = new T.Group();
    var hex = kind === 'entry' ? D.entryColor : D.exitColor;
    var dflt = kind === 'entry' ? '2fff6a' : 'ff9a2e';
    var y = floorAt(m.at) + 0.04, bh = D.beaconH || 2.1;
    var ring = new T.Mesh(new T.RingGeometry(0.38, 0.62, 28), mat(hex, dflt, {opacity: 0.8}));
    ring.rotation.x = -Math.PI / 2; ring.position.set(m.at[0], y + LIFT * 0.6, m.at[2]);
    grp.add(ring);
    var cyl = new T.Mesh(new T.CylinderGeometry(0.07, 0.07, bh, 8), mat(hex, dflt, {opacity: 0.45}));
    cyl.position.set(m.at[0], y + bh / 2, m.at[2]); grp.add(cyl);
    // the SEAM BAND at its real half-depth/half-width: a boundary you can side-step is a
    // camera that never changes, so its footprint has to be visible to be judged
    if (m.seam) {
      var n = m.seam.n, t = m.seam.t, w = m.seam.w;
      var ax = n[0], az = n[1], bx = -az, bz = ax;
      var corner = function (sa, sw) {
        return [m.at[0] + ax * t * sa + bx * w * sw, y + LIFT, m.at[2] + az * t * sa + bz * w * sw];
      };
      grp.add(line([corner(1, 1), corner(1, -1), corner(-1, -1), corner(-1, 1), corner(1, 1)],
                   lineMat(hex, dflt, {opacity: 0.7})));
    }
    if (m.aim) {
      var cone = new T.Mesh(new T.ConeGeometry(0.26, 0.85, 10), mat(hex, dflt, {opacity: 0.75}));
      cone.position.set(m.at[0] + m.aim[0] * 1.0, y + 0.95, m.at[2] + m.aim[1] * 1.0);
      cone.quaternion.setFromUnitVectors(new T.Vector3(0, 1, 0),
        new T.Vector3(m.aim[0], 0, m.aim[1]).normalize());     // point it the way the path leaves
      grp.add(cone);
    }
    var L = label(tag, hex, dflt);
    L.position.set(m.at[0], y + bh + 0.45, m.at[2]);
    grp.add(L);
    return grp;
  }

  function buildShot(id) {
    var T = TH(), S = DATA.shots[id], grp = new T.Group();
    grp.name = 'routes:' + id;
    if (!S) return grp;
    (S.routes || []).forEach(function (r) {
      var pts = lifted(r.points);
      if (pts.length < 2) return;
      if (r.role === 'blocked') {        // looks like a way on, refuses the player
        var lm = lineMat(D.blockedColor, 'ff4d4d', {opacity: 0.9});
        for (var i = 0; i + 1 < pts.length; i += 2) grp.add(line([pts[i], pts[i + 1]], lm));  // dashed by omission
        var L = label('NO ROUTE (' + r['class'] + ')', D.blockedColor, 'ff4d4d');
        L.position.set(pts[0][0], pts[0][1] + 1.6, pts[0][2]); grp.add(L);
        return;
      }
      var spur = r.role === 'spur';
      var hex = spur ? D.spurColor : D.routeColor, dflt = spur ? 'a8c8ff' : 'ffe08a';
      grp.add(ribbon(pts, (D.ribbonWidth || 0.55) * (spur ? 0.7 : 1), mat(hex, dflt, {opacity: spur ? 0.34 : 0.5})));
      grp.add(line(pts, lineMat(hex, dflt, {opacity: spur ? 0.7 : 1})));
    });
    (S.entries || []).forEach(function (e, i) {
      grp.add(marker(e, 'entry', 'IN ' + e.kind + (e.from ? ' ‹ ' + e.from : '')));
    });
    (S.exits || []).forEach(function (e) {
      grp.add(marker(e, 'exit', 'OUT ' + (e.prompt ? '[' + e.prompt + '] ' : '› ') + e.to));
    });
    return grp;
  }

  function rebuild() {
    var T = TH(), sc = SCN(); if (!T || !sc) return;
    if (!GROUP) { GROUP = new T.Group(); GROUP.name = 'routeOverlay'; GROUP.frustumCulled = false; sc.add(GROUP); }
    while (GROUP.children.length) GROUP.remove(GROUP.children[0]);
    var ids = wanted();
    for (var i = 0; i < ids.length; i++) {
      if (!BUILT[ids[i]]) BUILT[ids[i]] = buildShot(ids[i]);
      GROUP.add(BUILT[ids[i]]);
    }
    GROUP.visible = MODE !== 'off';
    legend(ids);
  }
  function legend(ids) {
    if (!LEGEND) {
      LEGEND = document.createElement('div');
      LEGEND.id = 'rlegend';
      LEGEND.style.cssText = 'position:fixed;bottom:8px;right:8px;z-index:3;font:12px monospace;' +
        'color:#e7ddd0;background:#000a;padding:8px 10px;border-radius:6px;line-height:1.7';
      document.body.appendChild(LEGEND);
    }
    LEGEND.style.display = MODE === 'off' ? 'none' : 'block';
    if (MODE === 'off' || !DATA) return;
    var S = DATA.shots[ids[0]] || {};
    LEGEND.innerHTML = '<b>ROUTES (R / Shift+R)</b> · ' + MODE + '<br>' +
      '<span style="color:#2fff6a">●</span> entry &nbsp; ' +
      '<span style="color:#ff9a2e">●</span> exit + band<br>' +
      '<span style="color:#ffe08a">▬</span> route &nbsp; ' +
      '<span style="color:#a8c8ff">▬</span> spur &nbsp; ' +
      '<span style="color:#ff4d4d">─</span> no route<br>' +
      (ids.length === 1 ? (S.name || ids[0]) + ' — ' + (S.entries || []).length + ' in / ' +
        (S.exits || []).length + ' out' : ids.length + ' shots') +
      '<br><span style="color:#a89179">' + (SRC || '') + '</span>';
  }

  function setMode(m) {
    if (m === MODE) return MODE;
    MODE = m;
    if (MODE === 'off') { if (GROUP) GROUP.visible = false; legend([]); return MODE; }
    load().then(function (j) { if (!j) { MODE = 'off'; return; } lastShot = shotId(); startPoll(); rebuild(); });
    return MODE;
  }
  // R cycles off/this shot; Shift+R adds the every-shot step. Checked against play3d.html:
  // w a s d, arrows, space, g, 2, [, ], m, z and e (the scene graph's interact key) are
  // taken; r is free.
  addEventListener('keydown', function (ev) {
    if (ev.repeat || ev.metaKey || ev.ctrlKey || ev.altKey) return;
    if ((ev.key || '').toLowerCase() !== KEY) return;
    if (ev.shiftKey) setMode(MODE === 'off' ? 'shot' : MODE === 'shot' ? 'all' : 'off');
    else setMode(MODE === 'off' ? 'shot' : 'off');
  });
  // a cut re-points the camera and changes which shot's routes are the right ones; poll
  // cheaply (1 Hz) instead of hooking the runtime, which this file must not touch
  var lastShot = null, POLL = null;
  function startPoll() {
    if (POLL) return;
    POLL = setInterval(function () {
      if (MODE === 'off' || !DATA) return;
      var s = shotId();
      if (s !== lastShot) { lastShot = s; rebuild(); }
    }, 1000);
  }

  // ============================================================ THE INSTRUMENT ====
  // GL READBACK visibility. Project a point, drop a magenta disc there, render once with
  // the depth test ON and once OFF, and compare the surviving pixels: the ratio is how
  // much of that point the shot's OWN BAKED DEPTH MAP leaves visible. This is the
  // SIM.paint() trick generalised from the character to the route, and it is why "entry
  // invisible" is a measurement in this audit and not an opinion.
  function readCount(gl, x0, y0, w, h) {
    var px = new Uint8Array(w * h * 4);
    gl.readPixels(x0, y0, w, h, gl.RGBA, gl.UNSIGNED_BYTE, px);
    var n = 0;
    for (var i = 0; i < w * h; i++) if (px[i * 4] > 200 && px[i * 4 + 2] > 200 && px[i * 4 + 1] < 80) n++;
    return n;
  }
  function visibleAt(p, r) {
    var T = TH(), sc = SCN(), ren = REN(), c = CAM(), S = SIM();
    if (!T || !sc || !ren || !c) return null;
    var gl = ren.getContext(), sz = new T.Vector2(); ren.getSize(sz);
    var Wf = sz.x, Hf = sz.y;
    var v = new T.Vector3(p[0], p[1], p[2]).project(c);
    var out = {ndc: [+v.x.toFixed(3), +v.y.toFixed(3)],
               onScreen: Math.abs(v.x) <= 1 && Math.abs(v.y) <= 1 && v.z < 1};
    if (!out.onScreen) { out.visibleFrac = 0; out.pixels = 0; out.of = 0; return out; }
    var geo = new T.SphereGeometry(r === undefined ? 0.26 : r, 10, 8);
    var mk = new T.Mesh(geo, new T.MeshBasicMaterial({color: 0xff00ff, depthTest: true, depthWrite: false}));
    mk.position.set(p[0], p[1], p[2]); mk.renderOrder = 997;
    var hidG = GROUP && GROUP.visible, chr = CH();
    if (GROUP) GROUP.visible = false;
    if (chr) chr.visible = false;                       // the player is not scenery
    sc.add(mk);
    var cx = Math.round((v.x * 0.5 + 0.5) * Wf), cy = Math.round((v.y * 0.5 + 0.5) * Hf);
    var w = 64, h = 64;
    var x0 = Math.max(0, Math.min(Wf - w, cx - (w >> 1))), y0 = Math.max(0, Math.min(Hf - h, cy - (h >> 1)));
    // SIM.depthQuad syncs the shot's depth uniforms and renders; in a real-time scene
    // there is no quad, so render directly. readPixels MUST happen in the same task as
    // the render — the drawing buffer is not preserved across a composite.
    var draw = function () { if (!(S && S.depthQuad && S.depthQuad(true))) ren.render(sc, c); };
    draw();
    out.pixels = readCount(gl, x0, y0, w, h);
    mk.material.depthTest = false;                       // reference: drawn at all
    draw();
    out.of = readCount(gl, x0, y0, w, h);
    sc.remove(mk); geo.dispose(); mk.material.dispose();
    if (chr) chr.visible = true;
    if (GROUP) GROUP.visible = !!hidG;
    out.visibleFrac = out.of ? Math.round(100 * out.pixels / out.of) / 100 : 0;
    out.window = [x0, y0, w, h];
    return out;
  }
  // Every metre of route, sampled: what fraction of the intended path is actually shown?
  function probeShot(id, stride) {
    var S = DATA && DATA.shots[id]; if (!S) return null;
    stride = Math.max(1, stride || 1);
    var lift = 0.9;                                     // knee height: what a player looks at
    var res = {shot: id, name: S.name, entries: [], exits: [], routes: [],
               cameraShot: shotId(), t: new Date().toISOString().slice(11, 19)};
    (S.entries || []).forEach(function (e) {
      var v = visibleAt([e.at[0], floorAt(e.at) + lift, e.at[2]]);
      res.entries.push({id: e.id, kind: e.kind, from: e.from, at: e.at,
        ndc: v && v.ndc, onScreen: v && v.onScreen, visibleFrac: v && v.visibleFrac,
        screen: e.screen});
    });
    (S.exits || []).forEach(function (e) {
      var v = visibleAt([e.at[0], floorAt(e.at) + lift, e.at[2]]);
      res.exits.push({id: e.id, kind: e.kind, to: e.to, prompt: e.prompt, at: e.at,
        ndc: v && v.ndc, onScreen: v && v.onScreen, visibleFrac: v && v.visibleFrac,
        screen: e.screen});
    });
    // TWO HEIGHTS, because they are two different questions and conflating them mis-grades
    // a shot. 0.35 = the route SURFACE: can a player see the path itself, the thing that
    // tells them where to walk before they walk it? 1.15 = the chest of a figure standing
    // there: can a player at least follow their own character along it? A near parapet
    // shot side-on (the Crossing) hides the first and not the second; a roof in the
    // foreground (Shelf-east) hides both.
    (S.routes || []).forEach(function (r) {
      if (r.role === 'blocked') return;
      var n = 0, on = 0, vis = 0, fig = 0, worstRun = 0, run = 0;
      for (var i = 0; i < r.points.length; i += stride) {
        var p = r.points[i], y = floorAt(p);
        var v = visibleAt([p[0], y + 0.35, p[2]], 0.22);
        var f = visibleAt([p[0], y + 1.15, p[2]], 0.3);
        n++;
        if (v && v.onScreen) on++;
        if (f && f.onScreen && f.visibleFrac >= 0.25) fig++;
        var seen = v && v.onScreen && v.visibleFrac >= 0.25;
        if (seen) { vis++; run = 0; } else { run++; if (run > worstRun) worstRun = run; }
      }
      res.routes.push({id: r.id, role: r.role, 'class': r['class'], length: r.length,
        samples: n, onScreenPct: n ? Math.round(1000 * on / n) / 10 : null,
        visiblePct: n ? Math.round(1000 * vis / n) / 10 : null,       // the surface
        figurePct: n ? Math.round(1000 * fig / n) / 10 : null,        // a player standing on it
        worstHiddenRun: worstRun, worstHiddenMetres: r.points.length > 1 ?
          Math.round(100 * worstRun * stride * (r.length / (r.points.length - 1))) / 100 : 0});
    });
    return res;
  }

  // ------------------------------------------------------- fall-off measure ----
  // The plan's bucket 1, made measurable. Step sideways off the route: if the player is
  // not BLOCKED by anything (a rail, a parapet, a wall) and there is no standable surface
  // within a step down, and the next floor below is more than `drop` metres away or absent
  // entirely — that is a place a player falls out of the world, with coordinates.
  function dropEdges(opt) {
    opt = opt || {};
    var drop = opt.drop === undefined ? 2.5 : opt.drop;
    var offs = opt.offsets || [0.9, 1.4, 2.0];
    var S = SIM(); if (!S || !DATA) return null;
    var ids = opt.shot ? [opt.shot] : wanted(), out = [];
    ids.forEach(function (id) {
      var R = DATA.shots[id]; if (!R) return;
      (R.routes || []).forEach(function (r) {
        if (r.role === 'blocked' || r.role === 'spur') return;
        for (var i = 0; i < r.points.length; i++) {
          var p = r.points[i], y = floorAt(p);
          var a = r.points[Math.max(0, i - 1)], b = r.points[Math.min(r.points.length - 1, i + 1)];
          var dx = b[0] - a[0], dz = b[2] - a[2], L = Math.hypot(dx, dz) || 1;
          var nx = -dz / L, nz = dx / L;
          for (var si = 0; si < 2; si++) {
            var sgn = si ? 1 : -1;
            for (var k = 0; k < offs.length; k++) {
              var x = p[0] + nx * offs[k] * sgn, z = p[2] + nz * offs[k] * sgn;
              if (S.blocked(x, z, y)) break;                            // rail / wall / parapet: protected
              if (S.ground(x, z, y) !== null) continue;                 // still floor: keep stepping out
              var below = (S.floors(x, z) || []).filter(function (v) { return v < y - 0.8; });
              var top = below.length ? Math.max.apply(null, below) : null;
              var fall = top === null ? 99 : y - top;
              if (fall >= drop) out.push({shot: id, route: r.id, at: [p[0], +y.toFixed(2), p[2]],
                edgeAt: [+x.toFixed(2), +z.toFixed(2)], side: sgn > 0 ? 'left' : 'right',
                offset: offs[k], fall: fall === 99 ? null : +fall.toFixed(1),
                bottomless: top === null});
              break;                                                    // first verdict per side wins
            }
          }
        }
      });
    });
    // one row per distinct place, so a straight 20 m rail is not reported 20 times
    var seen = {}, dedup = [];
    out.forEach(function (o) {
      var k = o.shot + '|' + o.side + '|' + Math.round(o.at[0] / 2) + '|' + Math.round(o.at[2] / 2);
      if (seen[k]) { seen[k].n++; return; }
      o.n = 1; seen[k] = o; dedup.push(o);
    });
    return {drop: drop, offsets: offs, places: dedup.length,
            samples: out.length, list: dedup};
  }

  window.ROUTES = {
    toggle: function (v) { return setMode(v === undefined ? (MODE === 'off' ? 'shot' : 'off') : (v ? 'shot' : 'off')); },
    mode: function (m) { return m === undefined ? MODE : setMode(m); },
    shot: shotId,
    src: function () { return SRC; },
    load: load,
    data: function () { return DATA; },
    rebuild: rebuild,
    visibleAt: visibleAt,
    probe: function (id, stride) {
      return load().then(function () {
        var s = id || (wanted()[0] || shotId());
        return probeShot(s, stride);
      });
    },
    dropEdges: function (o) { return load().then(function () { return dropEdges(o); }); },
    summary: function (id) {
      return load().then(function () {
        var s = id || (wanted()[0] || shotId());
        var p = probeShot(s, 1), d = dropEdges({shot: s});
        return {shot: s, probe: p, drops: d,
                measure: DATA && DATA.shots[s] && DATA.shots[s].measure};
      });
    }
  };
})();
